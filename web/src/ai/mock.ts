/**
 * DEV-ONLY stand-in for the AI server routes. Installed from main.tsx when import.meta.env.DEV.
 * Every AI request goes to the real server first; only when it answers 404 (routes not deployed yet)
 * does this answer instead, so the UI can be exercised before the server side exists.
 * Never active in production builds.
 */
import type { AiSettings, AiConversation } from './contract';
import { DEFAULT_MODELS } from './contract';

const AI_PATH = /^\/api\/v1\/(ai\/|admin\/ai\/|databases\/[^/]+\/ai-fill$)/;
const realFetch = window.fetch.bind(window);

const settings: AiSettings = {
  enabled: true,
  provider: 'mock',
  apiKey: { set: false, last4: null, source: null },
  bedrockRegion: 'eu-west-1',
  models: { ...DEFAULT_MODELS },
  features: { write: true, chat: true, autofill: true, agents: true },
  allowedRoles: ['owner', 'admin', 'member'],
  monthlyBudgetUsd: 200,
  perUserMonthlyBudgetUsd: 20,
};
let used = 3.42;
const conversations = new Map<string, AiConversation>();
const pendingConfirm = new Map<string, { convId: string; title: string }>();

const json = (body: unknown, status = 200) => new Response(JSON.stringify(body), { status, headers: { 'content-type': 'application/json' } });
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

function sse(run: (send: (event: string, data: unknown) => void) => Promise<void>, signal?: AbortSignal | null) {
  const enc = new TextEncoder();
  const stream = new ReadableStream({
    async start(ctrl) {
      const send = (event: string, data: unknown) => ctrl.enqueue(enc.encode(`event: ${event}\ndata: ${JSON.stringify(data)}\n\n`));
      try {
        await run((e, d) => {
          if (signal?.aborted) throw new DOMException('Aborted', 'AbortError');
          send(e, d);
        });
      } catch {}
      ctrl.close();
    },
  });
  return new Response(stream, { headers: { 'content-type': 'text/event-stream' } });
}

async function streamText(send: (e: string, d: unknown) => void, text: string) {
  for (const chunk of text.match(/.{1,12}/gs) ?? []) {
    send('delta', { text: chunk });
    await sleep(25);
  }
}

function writeResult(b: any): string {
  const t: string = (b.text ?? '').trim();
  switch (b.action) {
    case 'improve': return t ? `${t.charAt(0).toUpperCase()}${t.slice(1).replace(/\s+/g, ' ')}${/[.!?]$/.test(t) ? '' : '.'} (Improved for clarity.)` : 'Here is a clearer version.';
    case 'fix': return t.replace(/\bi\b/g, 'I').replace(/\s+/g, ' ');
    case 'shorter': return t.split(/(?<=[.!?])\s/).slice(0, 1).join(' ') || t.slice(0, 60);
    case 'longer': return `${t} In more detail, this means the team can move faster with fewer surprises, because everyone shares the same context.`;
    case 'tone': return `[${b.tone ?? 'professional'}] ${t}`;
    case 'translate': return `(${b.language ?? 'French'}) ${t}`;
    case 'summarize': case 'summarize_page': return `**Summary:** ${(t || b.context || 'This page').slice(0, 140)}…`;
    case 'explain': return `This means: ${t}`;
    case 'outline': return '## Outline\n\n1. Background\n2. Goals\n3. Plan\n4. Risks\n5. Next steps';
    case 'brainstorm': return '- Idea one: start small\n- Idea two: ask customers\n- Idea three: automate the boring parts';
    case 'action_items': return '- [ ] Share the plan with the team\n- [ ] Book a review for Friday\n- [ ] Update the roadmap';
    case 'continue': return ' And that is how we will get there, one step at a time.';
    default: return `${b.prompt ? `You asked: “${b.prompt}”.\n\n` : ''}${t || 'Here is a draft paragraph generated by the mock AI provider.'}`;
  }
}

async function chat(b: any, send: (e: string, d: unknown) => void) {
  let conv = b.conversationId ? conversations.get(b.conversationId) : undefined;
  if (!conv) {
    conv = { id: crypto.randomUUID(), title: String(b.message).slice(0, 48), mode: b.mode, updated_at: new Date().toISOString(), messages: [] };
    conversations.set(conv.id, conv);
  }
  conv.messages.push({ role: 'user', content: b.message });
  send('conversation', { id: conv.id, title: conv.title });
  const msg = String(b.message).toLowerCase();
  const steps: any[] = [];
  const search = await realFetch(`/api/v1/search?q=${encodeURIComponent(msg.split(/\s+/).filter((w) => w.length > 3)[0] ?? '')}`).then((r) => (r.ok ? r.json() : [])).catch(() => []);
  const sid = crypto.randomUUID();
  send('tool_call', { id: sid, name: 'search', summary: 'Searching the workspace…' });
  await sleep(300);
  send('tool_result', { id: sid, ok: true, summary: `Found ${search.length} page${search.length === 1 ? '' : 's'}` });
  steps.push({ call: { id: sid, name: 'search', summary: 'Searched the workspace' }, result: { id: sid, ok: true, summary: `Found ${search.length} pages` } });
  if (b.mode === 'agent' && /delete|remove|trash/.test(msg)) {
    const cid = crypto.randomUUID();
    pendingConfirm.set(cid, { convId: conv.id, title: search[0]?.title ?? 'that page' });
    send('confirm', { id: cid, name: 'delete-page', summary: `Move “${search[0]?.title ?? 'that page'}” to Trash`, input: { pageId: search[0]?.id } });
    return;
  }
  if (b.mode === 'agent' && /create|make|draft|write/.test(msg)) {
    const cid = crypto.randomUUID();
    send('tool_call', { id: cid, name: 'create-pages', summary: 'Creating a page…' });
    const page = await realFetch('/api/v1/pages', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ title: 'AI draft: ' + String(b.message).slice(0, 40), markdown: '## Draft\n\nCreated by the mock AI agent.' }) }).then((r) => r.json());
    send('tool_result', { id: cid, ok: true, summary: `Created “${page.title}”`, pageId: page.id });
    steps.push({ call: { id: cid, name: 'create-pages', summary: 'Created a page' }, result: { id: cid, ok: true, summary: `Created “${page.title}”`, pageId: page.id } });
    await streamText(send, `I created [${page.title}](/p/${page.id}) with a starter outline.`);
  } else {
    const top = search.slice(0, 3);
    const answer = top.length
      ? `Based on ${top.map((p: any) => `[${p.title || 'Untitled'}](/p/${p.id})`).join(', ')}:\n\n- This is a **mock** answer from the dev AI provider.\n- Configure a real provider in *Settings → AI*.\n\n\`\`\`\nexample code block\n\`\`\``
      : 'I could not find anything about that in the workspace. (Mock provider.)';
    await streamText(send, answer);
    send('citations', { pages: top.map((p: any) => ({ id: p.id, title: p.title || 'Untitled', icon: p.icon })) });
  }
  conv.messages.push({ role: 'assistant', content: '(mock answer)', steps });
  conv.updated_at = new Date().toISOString();
  used += 0.02;
  send('done', { usage: { input_tokens: 1200, output_tokens: 180, usd: 0.02 } });
}

async function aiFill(dbId: string, b: any) {
  const db = await realFetch(`/api/v1/databases/${dbId}`).then((r) => r.json());
  const prop = db.schema.find((p: any) => p.id === b.propId);
  const q = await realFetch(`/api/v1/databases/${dbId}/query`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: '{}' }).then((r) => r.json());
  const rows = q.rows.filter((r: any) => (!b.rowIds || b.rowIds.includes(r.id)) && (!b.onlyEmpty || r.props[b.propId] == null || r.props[b.propId] === ''));
  setTimeout(async () => {
    for (const r of rows) {
      await sleep(250);
      const value = prop?.ai?.kind === 'keywords' ? (r.title || 'untitled').toLowerCase().split(/\s+/).slice(0, 3).join(', ') : `AI: ${prop?.ai?.kind ?? 'summary'} of “${r.title || 'Untitled'}”`;
      await realFetch(`/api/v1/pages/${r.id}`, { method: 'PATCH', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ props: { [b.propId]: value } }) });
    }
  }, 0);
  return { queued: rows.length };
}

async function mockResponse(path: string, method: string, body: any, signal?: AbortSignal | null): Promise<Response> {
  if (path === '/api/v1/ai/status') {
    return json({ enabled: settings.enabled, provider: settings.provider, features: settings.features, models: settings.models, budget: { usedUsd: used, limitUsd: settings.monthlyBudgetUsd, userUsedUsd: used / 2, userLimitUsd: settings.perUserMonthlyBudgetUsd } });
  }
  if (path === '/api/v1/admin/ai/settings') {
    if (method === 'PUT') {
      const { apiKey, ...rest } = body ?? {};
      Object.assign(settings, rest);
      if (typeof apiKey === 'string') settings.apiKey = apiKey ? { set: true, last4: apiKey.slice(-4), source: 'db' } : { set: false, last4: null, source: null };
    }
    return json(settings);
  }
  if (path === '/api/v1/admin/ai/test') {
    await sleep(400);
    return json(settings.provider === 'mock' || settings.apiKey.set ? { ok: true, model: settings.models.fast, latencyMs: 412 } : { ok: false, error: 'No API key configured' });
  }
  if (path.startsWith('/api/v1/admin/ai/usage')) {
    const days = Array.from({ length: 14 }, (_, i) => ({ day: new Date(Date.now() - (13 - i) * 864e5).toISOString().slice(0, 10), usd: +(Math.abs(Math.sin(i)) * 0.6).toFixed(2), requests: 5 + i }));
    return json({
      from: days[0].day, to: days[13].day, totalUsd: used, requests: 180, tokens: { input: 412000, output: 61000 },
      byFeature: [{ feature: 'chat', usd: 1.9, requests: 70 }, { feature: 'write', usd: 0.8, requests: 85 }, { feature: 'autofill', usd: 0.5, requests: 20 }, { feature: 'agents', usd: 0.22, requests: 5 }],
      byUser: [{ userId: 'a', name: 'Justin', usd: 2.1, requests: 110 }, { userId: 'b', name: 'Priya Shah', usd: 1.32, requests: 70 }],
      byDay: days,
    });
  }
  if (path === '/api/v1/ai/write') return sse(async (send) => { await streamText(send, writeResult(body)); send('done', { usage: { usd: 0.001 } }); }, signal);
  if (path === '/api/v1/ai/chat') return sse((send) => chat(body, send), signal);
  const confirmM = path.match(/^\/api\/v1\/ai\/chat\/([^/]+)\/confirm$/);
  if (confirmM) {
    return sse(async (send) => {
      const p = pendingConfirm.get(body.toolCallId);
      pendingConfirm.delete(body.toolCallId);
      if (body.approve) {
        send('tool_result', { id: body.toolCallId, ok: true, summary: `Moved “${p?.title ?? 'page'}” to Trash (mock — nothing was deleted)` });
        await streamText(send, 'Done — it is in the Trash and can be restored for 30 days.');
      } else {
        send('tool_result', { id: body.toolCallId, ok: false, summary: 'Cancelled — you denied this action' });
        await streamText(send, 'Okay, I left it as it is.');
      }
      send('done', {});
    }, signal);
  }
  if (path === '/api/v1/ai/conversations') return json([...conversations.values()].sort((a, b) => b.updated_at.localeCompare(a.updated_at)).map(({ messages: _m, ...c }) => c));
  const convM = path.match(/^\/api\/v1\/ai\/conversations\/([^/]+)$/);
  if (convM) {
    if (method === 'DELETE') {
      conversations.delete(convM[1]);
      return json({ ok: true });
    }
    return conversations.has(convM[1]) ? json(conversations.get(convM[1])) : json({ error: 'Not found' }, 404);
  }
  const fillM = path.match(/^\/api\/v1\/databases\/([^/]+)\/ai-fill$/);
  if (fillM) return json(await aiFill(fillM[1], body));
  return json({ error: 'Not found' }, 404);
}

export function installAiDevMock() {
  window.fetch = async (input: RequestInfo | URL, init?: RequestInit) => {
    const url = typeof input === 'string' ? input : input instanceof URL ? input.href : input.url;
    const path = url.startsWith('http') ? new URL(url).pathname + new URL(url).search : url;
    const bare = path.split('?')[0];
    if (!AI_PATH.test(bare)) return realFetch(input, init);
    const res = await realFetch(input, init);
    if (res.status !== 404) return res;
    let body: any = undefined;
    try {
      body = init?.body ? JSON.parse(String(init.body)) : undefined;
    } catch {}
    console.info('[atrium] AI dev mock answering', init?.method ?? 'GET', bare);
    return mockResponse(path.startsWith('/api/v1/admin/ai/usage') ? path : bare, (init?.method ?? 'GET').toUpperCase(), body, init?.signal);
  };
}
